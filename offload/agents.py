"""Профили агентов OpenCode, которые `init` кладёт в проект.

Формат — по документации OpenCode v2: markdown-файл в `.opencode/agents/` с
правами в начале. Права строятся только на **явных запретах**: при запуске без
человека флаг `--auto` одобряет всё, что не запрещено прямо, и надеяться на
вопрос «разрешить?» нельзя — задать его некому.

Общий запрет один для всех ролей и обязателен: по умолчанию OpenCode разрешает
выход за пределы папки проекта (`external_directory`), и без правила ниже
исполнитель мог бы читать и писать где угодно.
"""

from __future__ import annotations

PREFIX = "offload-"

# Запреты, общие для всех ролей. Порядок важен: побеждает последнее совпавшее.
COMMON_DENY = [
    ("external_directory", "*"),
    ("read", "*.env"),
    ("read", "*.env.*"),
    ("read", "*.pem"),
    ("read", "*.key"),
    ("shell", "git push *"),
    ("shell", "git reset --hard *"),
    ("shell", "rm -rf *"),
]

ROLES: dict[str, dict] = {
    "explore": {
        "mode": "primary",
        "description": "Читает код и возвращает сводку. Ничего не меняет.",
        "deny": [("edit", "*"), ("shell", "*")],
        "prompt": (
            "Ты исследуешь код и отвечаешь оркестратору, а не человеку. "
            "Результат: сводка по пунктам с путями файлов и номерами строк. "
            "Без вступлений, без пересказа задания, без объяснения базовых вещей. "
            "Не знаешь — так и пиши, не додумывай."
        ),
    },
    "plan": {
        "mode": "primary",
        "description": "Читает код и возвращает план работ. Ничего не меняет.",
        "deny": [("edit", "*"), ("shell", "*")],
        "prompt": (
            "Ты составляешь план для оркестратора. Результат: пронумерованные шаги, "
            "у каждого — файлы и способ проверить, что шаг сделан. Отдельно: риски "
            "и вопросы, без ответов на которые начинать нельзя. Без воды."
        ),
    },
    "build": {
        "mode": "primary",
        "description": "Реализует задание и гоняет проверку до зелёного результата.",
        "deny": [],
        "prompt": (
            "Ты исполнитель. Пиши отчёт оркестратору строго по формату из "
            ".offload/protocol.md: СДЕЛАНО / ПРОВЕРЕНО / НЕ СДЕЛАНО / РЕШЕНИЯ / БЛОКЕРЫ. "
            "В ПРОВЕРЕНО вставляй настоящий вывод команд, а не слова «всё работает». "
            "Не подгоняй код под тесты: если тест неверен — скажи об этом в БЛОКЕРЫ. "
            "Правь только то, что в задании."
        ),
    },
    "review": {
        "mode": "primary",
        "description": "Проверяет чужие изменения и перечисляет проблемы. Ничего не меняет.",
        "deny": [("edit", "*")],
        "prompt": (
            "Ты ревьюер для оркестратора. Результат: список находок по убыванию "
            "важности, у каждой файл, строка и чем это плохо. Нет находок — так и "
            "напиши одной строкой. Не хвали и не пересказывай изменения."
        ),
    },
}


def render(role: str) -> str:
    spec = ROLES[role]
    rules = [("deny", action, resource) for action, resource in COMMON_DENY + spec["deny"]]
    lines = ["---", f"description: {spec['description']}", f"mode: {spec['mode']}", "permissions:"]
    for effect, action, resource in rules:
        lines += [
            f"  - action: {action}",
            f'    resource: "{resource}"',
            f"    effect: {effect}",
        ]
    lines += ["---", "", spec["prompt"], ""]
    return "\n".join(lines)


def files() -> dict[str, str]:
    """Имя файла → содержимое для всех ролей."""
    return {f"{PREFIX}{role}.md": render(role) for role in ROLES}
